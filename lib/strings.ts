export function t(language: string | null | undefined, key: string, params: TranslationParams = {}) {
  const normalized = normalizeLanguage(language);
  const localizedMessage = resolveTranslation(normalized, key);
  const fallbackMessage = normalized === defaultLanguage ? null : resolveTranslation(defaultLanguage, key);
  const message = localizedMessage ?? fallbackMessage;

  if (!message) {
    if (process.env.NODE_ENV !== "production") {
      console.warn(`Missing translation key: ${key}`);
    }
    return key;
  }

  if (!localizedMessage && fallbackMessage && process.env.NODE_ENV !== "production") {
    console.warn(`Missing translation key for ${normalized}: ${key}`);
  }

  const pluralCount = typeof params.count !== "undefined" ? Number(params.count) : Number(params.joinedCount);
  const template = typeof message === "string" ? message : pluralCount === 1 ? message.one : message.other;
  return interpolate(template, params);
}

