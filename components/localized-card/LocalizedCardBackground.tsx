function LocalizedCardBackgroundComponent({
  theme,
  className,
  preserveRightControlZone = true
}: LocalizedCardBackgroundProps) {
  const isLightTheme = isLightLocalizedCardTheme(theme);
  const patternOpacities = getPatternOpacities(theme, isLightTheme);

  return (
    <div className={`pointer-events-none absolute inset-0 overflow-hidden ${className ?? ""}`.trim()} aria-hidden>
      <div className="absolute inset-0 bg-[var(--localized-card-bg)]" />
      <div className="absolute inset-0">
        <svg
          viewBox="0 0 587.16 163.41"
          className="absolute left-1/2 top-1/2 h-[118%] w-[111%] -translate-x-1/2 -translate-y-1/2"
          preserveAspectRatio="xMidYMid slice"
          style={{
            filter: isLightTheme ? "saturate(1.18) contrast(1.03)" : undefined
          }}
        >
          <g style={getPatternFadeStyle(preserveRightControlZone)}>
            <LocalizedEmblem theme={theme} variant="card" />
            {PATTERN_LAYER_PATHS.map((layer, index) => (
              <path key={index} d={layer.d} fill={layer.fill} opacity={patternOpacities[index] ?? 1} />
            ))}
          </g>
        </svg>
      </div>
      {preserveRightControlZone ? (
        <div
          className="absolute inset-y-0 right-0 w-[32%]"
          style={{
            background: isLightTheme
              ? "linear-gradient(90deg, rgba(255,255,255,0) 0%, rgba(255,255,255,0.008) 70%, var(--localized-card-control-zone-tint) 90%, rgba(255,255,255,0.035) 100%)"
              : "linear-gradient(90deg, rgba(255,255,255,0) 0%, rgba(255,255,255,0.015) 66%, var(--localized-card-control-zone-tint) 88%, rgba(255,255,255,0.09) 100%)"
          }}
        />
      ) : null}
    </div>
  );
}

export const LocalizedCardBackground = memo(LocalizedCardBackgroundComponent);

function getPatternOpacities(theme: LocalizedCardTheme, isLightTheme: boolean) {
  if (isLightTheme) {
    if (theme.id === "japan") {
      return [0.86, 1, 0.9, 0.24, 0.82, 0.9, 0.24, 0.64, 0.58];
    }

    return [0.66, 1, 0.96, 0.34, 0.9, 0.98, 0.42, 0.2, 0.18];
  }

  if (theme.id === "germany") {
    return [1, 0.96, 0.9, 0.28, 0.78, 0.92, 0.34, 0.16, 0.14];
  }

  return [0.56, 0.96, 0.9, 0.28, 0.78, 0.92, 0.34, 0.16, 0.14];
}

function getPatternFadeStyle(preserveRightControlZone: boolean): CSSProperties | undefined {
  if (!preserveRightControlZone) {
    return undefined;
  }

  return {
    WebkitMaskImage:
      "linear-gradient(90deg, rgba(0,0,0,1) 0%, rgba(0,0,0,1) 78%, rgba(0,0,0,0.96) 88%, rgba(0,0,0,0.88) 100%)",
    maskImage:
      "linear-gradient(90deg, rgba(0,0,0,1) 0%, rgba(0,0,0,1) 78%, rgba(0,0,0,0.96) 88%, rgba(0,0,0,0.88) 100%)"
  };
}
